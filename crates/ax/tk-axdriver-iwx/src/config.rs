/// Match the complete OpenBSD iwx runtime table, from last entry to first.
// upstream: if_iwx.c iwx_find_device_cfg()
pub fn lookup_config(runtime: RuntimeConfig) -> Option<DeviceConfig> {
    for info in DEVICE_INFO_TABLE.iter().rev() {
        if info.matches(runtime) {
            return Some(info.config);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;
    const AX211: RuntimeConfig = RuntimeConfig::from_hardware(0x54f0, 0x4070, 0x43, 0, 0x10d, 0, 0);
    #[test]
    fn full_source_table_is_kept_in_order() {
        assert_eq!(DEVICE_INFO_TABLE.len(), 97);
    }
    #[test]
    fn matches_full_openbsd_pci_attach_list() {
        assert!(matches_pci_device(INTEL_VENDOR_ID, AX211_DEVICE_ID));
        assert!(matches_pci_device(INTEL_VENDOR_ID, 0x2723));
        assert!(!matches_pci_device(0xffff, 0x54f0));
        assert!(!matches_pci_device(INTEL_VENDOR_ID, 0xffff));
    }
    #[test]
    fn ax211_runtime_selects_so_gf_and_linux_firmware_api89() {
        assert_eq!(lookup_config(AX211), Some(DeviceConfig::SoGfAx211));
        let fw = DeviceConfig::SoGfAx211.firmware();
        assert_eq!(fw.firmware, "/lib/firmware/iwlwifi-so-a0-gf-a0-89.ucode");
        assert_eq!(fw.pnvm, Some("/lib/firmware/iwlwifi-so-a0-gf-a0.pnvm"));
        assert!(fw.uhb_supported);
    }
    #[test]
    fn attach_profile_combines_product_defaults_with_runtime_firmware_config() {
        let profile = attach_profile(AX211).unwrap();
        assert_eq!(profile.config, DeviceConfig::SoGfAx211);
        assert_eq!(profile.family, crate::DeviceFamily::Ax210);
        assert!(!profile.integrated);
        assert_eq!(profile.mac_addr_from_csr, 0x380);
        assert_eq!(profile.umac_prph_offset, 0x300000);
        assert_eq!(profile.max_tfd_queue_size, crate::GEN3_MAX_TFD_QUEUE_SIZE);
        assert!(profile.uhb_supported);
        assert_eq!(
            profile.firmware.firmware,
            "/lib/firmware/iwlwifi-so-a0-gf-a0-89.ucode"
        );
        assert_eq!(
            attach_profile(RuntimeConfig::from_hardware(0xffff, 0, 0, 0, 0, 0, 0)),
            Err(AttachProfileError::UnknownProduct(0xffff))
        );
    }
    #[test]
    fn exact_killer_1691_1692_1671_1672_rows_win_in_reverse_order() {
        for sub in [0x1691, 0x1692] {
            assert_eq!(
                lookup_config(RuntimeConfig {
                    subdevice: sub,
                    cdb: 1,
                    ..AX211
                }),
                Some(DeviceConfig::SoGf4Ax411)
            );
        }
        for sub in [0x1671, 0x1672] {
            assert_eq!(
                lookup_config(RuntimeConfig {
                    subdevice: sub,
                    ..AX211
                }),
                Some(DeviceConfig::SoGfAx211)
            );
        }
    }
    #[test]
    fn distinct_so_and_sof_mac_types_both_match_their_source_rows() {
        let so = RuntimeConfig {
            mac_type: 0x37,
            ..AX211
        };
        assert_eq!(lookup_config(so), Some(DeviceConfig::SoGfAx211));
        assert_eq!(lookup_config(RuntimeConfig { no_160: 1, ..AX211 }), None);
        assert_eq!(
            lookup_config(RuntimeConfig {
                rf_type: 0,
                ..AX211
            }),
            None
        );
        assert_eq!(
            lookup_config(RuntimeConfig {
                mac_type: 0,
                ..AX211
            }),
            None
        );
    }
}

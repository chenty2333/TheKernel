/// Intel PCI vendor ID used by the OpenBSD `iwx_devices` table.
pub const INTEL_VENDOR_ID: u16 = 0x8086;
/// AX211 PCI product ID `PCI_PRODUCT_INTEL_WL_22500_16`.
pub const AX211_DEVICE_ID: u16 = 0x54f0;

const PCI_PRODUCT_IDS: &[u16] = &[
    0x2723, 0x02f0, 0xa0f0, 0x34f0, 0x06f0, 0x43f0, 0x3df0, 0x4df0, 0x2725, 0x2726, 0x51f0, 0x7a70,
    0x51f1, 0x7af0, 0x7e40, 0x54f0, 0x7f70, 0x7740,
];

/// Whether a PCI function belongs to OpenBSD's full iwx attach ID list.
// upstream: if_iwx.c iwx_match()
pub const fn matches_pci_device(vendor_id: u16, device_id: u16) -> bool {
    if vendor_id != INTEL_VENDOR_ID {
        return false;
    }
    let mut i = 0;
    while i < PCI_PRODUCT_IDS.len() {
        if PCI_PRODUCT_IDS[i] == device_id {
            return true;
        }
        i += 1;
    }
    false
}


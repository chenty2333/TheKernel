#[repr(C)]
#[derive(Clone, Copy)]
struct CmdBitmask {
    offset: u32,
    mask: u32,
    expected: u32,
    condition_offset: u32,
    condition_mask: u32,
}

impl CmdBitmask {
    const ZERO: Self = Self {
        offset: 0,
        mask: 0,
        expected: 0,
        condition_offset: 0,
        condition_mask: 0,
    };
}

#[repr(C)]
#[derive(Clone, Copy)]
struct DrmI915CmdDescriptor {
    flags: u32,
    cmd_value: u32,
    cmd_mask: u32,
    length: u32,
    reg_offset: u32,
    reg_mask: u32,
    reg_step: u32,
    bits: [CmdBitmask; 3],
}

const _: [(); 88] = [(); core::mem::size_of::<DrmI915CmdDescriptor>()];

#[repr(C)]
struct DrmI915CmdTable {
    table: *const DrmI915CmdDescriptor,
    count: c_int,
}
unsafe impl Sync for DrmI915CmdTable {}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct DrmI915RegDescriptor {
    pub addr: u32,
    pub mask: u32,
    pub value: u32,
}
const _: [(); 12] = [(); core::mem::size_of::<DrmI915RegDescriptor>()];

#[repr(C)]
pub struct DrmI915RegTable {
    pub regs: *const DrmI915RegDescriptor,
    pub num_regs: c_int,
}
unsafe impl Sync for DrmI915RegTable {}

#[repr(C)]
struct CmdNode {
    desc: *const DrmI915CmdDescriptor,
    node: HlistNode,
}

const fn bitmask(
    offset: u32,
    mask: u32,
    expected: u32,
    condition_offset: u32,
    condition_mask: u32,
) -> CmdBitmask {
    CmdBitmask {
        offset,
        mask,
        expected,
        condition_offset,
        condition_mask,
    }
}
const fn descriptor(
    flags: u32,
    value: u32,
    mask: u32,
    length: u32,
    reg_offset: u32,
    reg_mask: u32,
    reg_step: u32,
    bits: [CmdBitmask; 3],
) -> DrmI915CmdDescriptor {
    DrmI915CmdDescriptor {
        flags,
        cmd_value: value,
        cmd_mask: mask,
        length,
        reg_offset,
        reg_mask,
        reg_step,
        bits,
    }
}


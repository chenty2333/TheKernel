// upstream: i915_cmd_parser.c gen7_render_get_cmd_length_mask()
unsafe extern "C" fn gen7_render_get_cmd_length_mask(cmd_header: u32) -> u32 {
    let client = cmd_header >> INSTR_CLIENT_SHIFT;
    let subclient = (cmd_header & INSTR_SUBCLIENT_MASK) >> INSTR_SUBCLIENT_SHIFT;
    if client == INSTR_MI_CLIENT {
        0x3f
    } else if client == INSTR_RC_CLIENT {
        if subclient == INSTR_MEDIA_SUBCLIENT {
            0xffff
        } else {
            0xff
        }
    } else {
        drm_dbg!(
            ptr::null_mut::<core::ffi::c_void>(),
            "CMD: Abnormal rcs cmd length! 0x%08X\n",
            cmd_header
        );
        0
    }
}

// upstream: i915_cmd_parser.c gen7_bsd_get_cmd_length_mask()
unsafe extern "C" fn gen7_bsd_get_cmd_length_mask(cmd_header: u32) -> u32 {
    let client = cmd_header >> INSTR_CLIENT_SHIFT;
    let subclient = (cmd_header & INSTR_SUBCLIENT_MASK) >> INSTR_SUBCLIENT_SHIFT;
    let op = (cmd_header & INSTR_26_TO_24_MASK) >> INSTR_26_TO_24_SHIFT;
    if client == INSTR_MI_CLIENT {
        0x3f
    } else if client == INSTR_RC_CLIENT {
        if subclient == INSTR_MEDIA_SUBCLIENT {
            if op == 6 { 0xffff } else { 0xfff }
        } else {
            0xff
        }
    } else {
        drm_dbg!(
            ptr::null_mut::<core::ffi::c_void>(),
            "CMD: Abnormal bsd cmd length! 0x%08X\n",
            cmd_header
        );
        0
    }
}


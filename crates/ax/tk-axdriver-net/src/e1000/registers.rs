/// Queue-register offsets from the Intel shared register header.
// upstream: e1000_regs.h E1000_RDBAL() and E1000_TDBAL()
const fn queue_reg(queue: u32, low: u32, high: u32) -> u32 {
    if queue < 4 {
        low + queue * 0x100
    } else {
        high + queue * 0x40
    }
}

/// Receive descriptor ring base low register offset.
// upstream: e1000_regs.h E1000_RDBAL()
pub const fn rx_desc_base_low(queue: u32) -> u32 {
    queue_reg(queue, 0x02800, 0x0c000)
}
/// Receive descriptor ring base high register offset.
// upstream: e1000_regs.h E1000_RDBAH()
pub const fn rx_desc_base_high(queue: u32) -> u32 {
    queue_reg(queue, 0x02804, 0x0c004)
}
